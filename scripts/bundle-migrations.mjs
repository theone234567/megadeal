// Writes lib/db/migrationFiles.ts: every file in supabase/migrations, as
// text, so the site itself can apply them (Admin > Moving off Wix >
// "Apply database updates") with no terminal. A Worker has no file system
// to read them from. lib/db/migrationFiles.test.ts fails until it's rerun
// after a migration is added or changed:
//
//   node scripts/bundle-migrations.mjs
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "supabase", "migrations");
const files = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((file) => ({ file, sql: readFileSync(join(dir, file), "utf8") }));

const body = `// Generated by scripts/bundle-migrations.mjs from supabase/migrations: don't edit.
import type { MigrationFile } from "./migrate";

export const MIGRATION_FILES: MigrationFile[] = ${JSON.stringify(files, null, 2)};
`;
writeFileSync(join(process.cwd(), "lib", "db", "migrationFiles.ts"), body);
console.log(`lib/db/migrationFiles.ts: ${files.length} migrations`);
